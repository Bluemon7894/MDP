type Pt = [number, number]
interface Part { pts: Pt[]; fill: boolean }

const rad = (d: number) => (d * Math.PI) / 180
const close = (pts: Pt[]): Pt[] => {
  const a = pts[0], b = pts[pts.length - 1]
  return a[0] === b[0] && a[1] === b[1] ? pts : [...pts, a]
}
const S = (pts: Pt[]): Part => ({ pts, fill: false })
const F = (pts: Pt[]): Part => ({ pts: close(pts), fill: true })

const ell = (cx: number, cy: number, rx: number, ry: number, rot = 0, n = 40): Pt[] => {
  const c = Math.cos(rad(rot)), s = Math.sin(rad(rot))
  return Array.from({ length: n + 1 }, (_, i) => {
    const a = (i / n) * Math.PI * 2
    const x = Math.cos(a) * rx, y = Math.sin(a) * ry
    return [cx + x * c - y * s, cy + x * s + y * c] as Pt
  })
}
const arc = (cx: number, cy: number, rx: number, ry: number, a0: number, a1: number, n = 24): Pt[] =>
  Array.from({ length: n + 1 }, (_, i) => {
    const a = rad(a0 + ((a1 - a0) * i) / n)
    return [cx + Math.cos(a) * rx, cy + Math.sin(a) * ry] as Pt
  })
const rect = (x1: number, y1: number, x2: number, y2: number): Pt[] => [[x1, y1], [x2, y1], [x2, y2], [x1, y2]]
const poly = (cx: number, cy: number, r: number, n: number, rot = -90): Pt[] =>
  Array.from({ length: n }, (_, i) => [cx + Math.cos(rad(rot + (360 * i) / n)) * r, cy + Math.sin(rad(rot + (360 * i) / n)) * r] as Pt)
const rrect = (x1: number, y1: number, x2: number, y2: number, r: number): Pt[] => [
  ...arc(x2 - r, y1 + r, r, r, -90, 0, 6),
  ...arc(x2 - r, y2 - r, r, r, 0, 90, 6),
  ...arc(x1 + r, y2 - r, r, r, 90, 180, 6),
  ...arc(x1 + r, y1 + r, r, r, 180, 270, 6),
]
const star = (cx: number, cy: number, R: number, r: number): Pt[] =>
  Array.from({ length: 10 }, (_, i) => {
    const a = rad(-90 + 36 * i), k = i % 2 ? r : R
    return [cx + Math.cos(a) * k, cy + Math.sin(a) * k] as Pt
  })
// Catmull-Rom 스플라인으로 컨트롤 포인트를 부드러운 곡선으로 변환
const smooth = (pts: Pt[], closed: boolean, steps = 8): Pt[] => {
  const n = pts.length
  const at = (i: number) => (closed ? pts[(i + n) % n] : pts[Math.max(0, Math.min(n - 1, i))])
  const out: Pt[] = []
  const last = closed ? n : n - 1
  for (let i = 0; i < last; i++) {
    const p0 = at(i - 1), p1 = at(i), p2 = at(i + 1), p3 = at(i + 2)
    for (let s = 0; s < steps; s++) {
      const t = s / steps, t2 = t * t, t3 = t2 * t
      const f = (a: number, b: number, c: number, d: number) =>
        0.5 * (2 * b + (-a + c) * t + (2 * a - 5 * b + 4 * c - d) * t2 + (-a + 3 * b - 3 * c + d) * t3)
      out.push([f(p0[0], p1[0], p2[0], p3[0]), f(p0[1], p1[1], p2[1], p3[1])])
    }
  }
  out.push(closed ? pts[0] : pts[n - 1])
  return out
}
const ring = (r1: number, r2: number, cx = 128, cy = 200): Pt[] => [...arc(cx, cy, r1, r1, 180, 360), ...arc(cx, cy, r2, r2, 360, 180)]

