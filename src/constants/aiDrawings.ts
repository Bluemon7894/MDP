const SCALE = 2.6

export type CanvasPt = Pt

/**
 * 제시어의 로컬 벡터를 캔버스 좌표로 변환한다.
 *  fills: 명암을 칠할 닫힌 도형(even-odd), lines: 디테일 선, strokes: 신경망 판정용 256x256 좌표 [xs, ys, ts]
 */
export function getAiShape(en: string, canvasW: number, canvasH: number) {
  const parts = DRAWINGS[norm(en)] ?? []
  const doodle = DOODLES[norm(en)]
  const offX = (canvasW - 256 * SCALE) / 2
  const offY = (canvasH - 256 * SCALE) / 2
  const tx = (p: Pt): Pt => [offX + p[0] * SCALE, offY + p[1] * SCALE]

  const fills = parts.filter(p => p.fill).map(p => p.pts.map(tx))
  const lines = parts.filter(p => !p.fill).map(p => p.pts.map(tx))
  // 낙서를 캔버스 좌표로 (사진이 없는 제시어는 이 낙서를 연필 선화로 그린다)
  // Quick, Draw! 낙서는 왼쪽 위에 붙어 있어서 그림 영역 가운데로 옮긴다
  let doodleLines: Pt[][] = []
  if (doodle) {
    const all = doodle.strokes.flatMap(([xs, ys]) => xs.map((x, k) => [x, ys[k]] as Pt))
    const minX = Math.min(...all.map(p => p[0])), maxX = Math.max(...all.map(p => p[0]))
    const minY = Math.min(...all.map(p => p[1])), maxY = Math.max(...all.map(p => p[1]))
    const dx = (256 - (maxX - minX)) / 2 - minX, dy = (256 - (maxY - minY)) / 2 - minY
    doodleLines = doodle.strokes.map(([xs, ys]) => xs.map((x, k) => tx([x + dx, ys[k] + dy])))
  }

  // 인식용 획: 검증된 사람 낙서가 있으면 그것, 없으면 벡터 도형
  // 사람이 그은 선처럼 촘촘하게 다시 샘플링해야 Quick, Draw! 가 낙서로 오인하지 않는다
  const source: { pts: Pt[] }[] = doodle ? doodle.strokes.map(([xs, ys]) => ({ pts: xs.map((x, k) => [x, ys[k]] as Pt) })) : parts
  const strokes: number[][][] = source.map(part => {
    const x: number[] = [], y: number[] = []
    part.pts.forEach((p, i) => {
      const q = part.pts[i + 1]
      if (!q) {
        x.push(Math.round(p[0]))
        y.push(Math.round(p[1]))
        return
      }
      const n = Math.max(1, Math.ceil(Math.hypot(q[0] - p[0], q[1] - p[1]) / 4))
      for (let k = 0; k < n; k++) {
        x.push(Math.round(p[0] + ((q[0] - p[0]) * k) / n))
        y.push(Math.round(p[1] + ((q[1] - p[1]) * k) / n))
      }
    })
    return [x, y, x.map((_, i) => i * 12)]
  })

  return { fills, lines, doodleLines, strokes, complexity: source.length }
}
