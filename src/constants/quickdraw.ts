// ── 빠른 검색을 위한 사전 맵 생성 ──────────────────────────────────────────
export const QUICKDRAW_DICT: Record<string, string> = {}

const normKey = (s: string) => s.toLowerCase().replace(/[\s_\-]+/g, '')

;[...GUESS_ONLY, ...ALL_QUICKDRAW_DATASET].forEach(item => {
  QUICKDRAW_DICT[normKey(item.en)] = item.ko
})

// ── 영어 라벨을 한글로 매핑하는 헬퍼 함수 (사전에 없는 라벨도 영어로 노출하지 않는다) ──
export function toKorean(enWord: string): string {
  if (!enWord) return ''
  return QUICKDRAW_DICT[normKey(enWord)] || '알 수 없는 그림'
}

// ── 게임 라운드용 무작위 제시어 선택 함수 (Fisher-Yates 셔플) ──────────────
export function pickRandomKeywords(count = 10): KeywordMap[] {
  const shuffled = [...ALL_QUICKDRAW_DATASET]
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]]
  }
  return shuffled.slice(0, count)
}